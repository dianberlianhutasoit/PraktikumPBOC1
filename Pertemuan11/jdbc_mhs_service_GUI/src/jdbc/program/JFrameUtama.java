    // Menampilkan seluruh data mahasiswa dari database ke JList
    private void tampilSemuaData() {
        modelId.clear(); // Mengosongkan JList ID sebelum data baru ditampilkan
        modelNama.clear(); // Mengosongkan JList nama sebelum data baru ditampilkan

        List<Mahasiswa> listMahasiswa = service.getAll(); // Mengambil semua data mahasiswa dari database

        for (Mahasiswa mhs : listMahasiswa) {
            modelId.addElement(String.valueOf(mhs.getId())); // Menampilkan ID mahasiswa ke JList ID
            modelNama.addElement(mhs.getNama()); // Menampilkan nama mahasiswa ke JList nama
        }
    }
    
    // Mengisi TextField edit dan hapus berdasarkan data yang dipilih di JList
    private void pilihData(int index) {
        if (index >= 0 && index < modelId.getSize()) {
            String id = modelId.getElementAt(index); // Mengambil ID berdasarkan index pilihan
            String nama = modelNama.getElementAt(index); // Mengambil nama berdasarkan index pilihan

            jTextFieldIdEdit.setText(id); // Mengisi ID ke field edit
            jTextFieldNamaEdit.setText(nama); // Mengisi nama ke field edit

            jTextFieldIdHapus.setText(id); // Mengisi ID ke field hapus
            jTextFieldNamaHapus.setText(nama); // Mengisi nama ke field hapus
        }
    }

