    private void jButtonTambahkanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonTambahkanActionPerformed
        String nama = jTextFieldNama.getText(); // Mengambil nama dari TextField

        Mahasiswa mhs = new Mahasiswa(); 
        mhs.setNama(nama); 
        service.add(mhs); // Menyimpan data mahasiswa ke database

        tampilSemuaData(); // Menampilkan ulang data setelah insert
        jTextFieldNama.setText(""); 
    }//GEN-LAST:event_jButtonTambahkanActionPerformed

    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        int id = Integer.parseInt(jTextFieldIdEdit.getText()); // Mengambil ID mahasiswa yang akan diubah
        String nama = jTextFieldNamaEdit.getText(); 
        Mahasiswa mhs = new Mahasiswa(id, nama); // Membuat objek mahasiswa dengan ID dan nama baru
        
        service.update(mhs); // Mengubah data mahasiswa di database
        tampilSemuaData(); // Menampilkan ulang data setelah update
        jTextFieldIdEdit.setText(""); 
        jTextFieldNamaEdit.setText(""); 
    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonHapusActionPerformed
        int index = jListId.getSelectedIndex(); // Mengambil posisi ID yang dipilih
        int id = Integer.parseInt(modelId.getElementAt(index)); // Mengambil ID dari JList berdasarkan posisi

        service.delete(id); // Menghapus data mahasiswa berdasarkan ID
        tampilSemuaData(); 
    }//GEN-LAST:event_jButtonHapusActionPerformed

    private void jButtonResetIndeksActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonResetIndeksActionPerformed
        service.indexReset(); // Memanggil method untuk mereset indeks tabel mahasiswa

        jLabelInfoReset.setText("Index di reset ke 0");
    }//GEN-LAST:event_jButtonResetIndeksActionPerformed

    private void jListIdValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jListIdValueChanged
        if (!evt.getValueIsAdjusting()) {
            int index = jListId.getSelectedIndex(); // Mengambil posisi ID yang dipilih

            jListNama.setSelectedIndex(index); // Menyamakan pilihan pada JList Nama
            pilihData(index); // Mengisi data ke TextField edit dan hapus
        }
    }//GEN-LAST:event_jListIdValueChanged

    private void jListNamaValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_jListNamaValueChanged
        if (!evt.getValueIsAdjusting()) {
            int index = jListNama.getSelectedIndex(); // Mengambil posisi nama yang dipilih

            jListId.setSelectedIndex(index); // Menyamakan pilihan pada JList ID
            pilihData(index); // Mengisi data ke TextField edit dan hapus
        }
    }//GEN-LAST:event_jListNamaValueChanged

